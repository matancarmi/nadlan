def seed_planning_stages(db: Session) -> None:
    for stage in STAGES:
        existing = db.query(PlanningStage).filter_by(key=stage["key"]).one_or_none()
        if existing:
            for k, v in stage.items():
                setattr(existing, k, v)
        else:
            db.add(PlanningStage(**stage))
    db.commit()
